def motions(graph, agent, p):
    """Wait or orthogonal neighbor; bridge direction cannot reverse."""
    if p == agent.goal:
        return (p,)
    out=[]
    forward = 1 if agent.goal[0]>agent.start[0] else -1
    for q in (p,*sorted(graph.neighbors(p))):
        if 3<=p[0]<=11 and p[1]==2 and (q[0]-p[0])*forward < 0:
            continue
        out.append(q)
    return tuple(out)


def boundaries(graph):
    """Exterior (free-space union) unit-square boundary segments."""
    free=graph.cells
    b=[]
    for x,y in sorted(free):
        if (x+1,y) not in free: b.append(((x+.5,y-.5),(x+.5,y+.5)))
        if (x-1,y) not in free: b.append(((x-.5,y-.5),(x-.5,y+.5)))
        if (x,y+1) not in free: b.append(((x-.5,y+.5),(x+.5,y+.5)))
        if (x,y-1) not in free: b.append(((x-.5,y-.5),(x+.5,y-.5)))
    return tuple(b)


def _point_to_segment(p,a,b):
    ab=(b[0]-a[0],b[1]-a[1]); den=ab[0]**2+ab[1]**2
    f=max(0.,min(1.,((p[0]-a[0])*ab[0]+(p[1]-a[1])*ab[1])/den)) if den else 0.
    return math.hypot(p[0]-a[0]-f*ab[0],p[1]-a[1]-f*ab[1])


def _segments_intersect(a,b,c,d):
    def cross(p,q,r):return (q[0]-p[0])*(r[1]-p[1])-(q[1]-p[1])*(r[0]-p[0])
    x1=cross(a,b,c);x2=cross(a,b,d);x3=cross(c,d,a);x4=cross(c,d,b)
    # Collinear overlap is detected by endpoint distances == 0 later.
    return ((x1>0 and x2<0 or x1<0 and x2>0) and (x3>0 and x4<0 or x3<0 and x4>0))


def segment_distance(a,b,c,d):
    if _segments_intersect(a,b,c,d):return 0.
    return min(_point_to_segment(a,c,d),_point_to_segment(b,c,d),
               _point_to_segment(c,a,b),_point_to_segment(d,a,b))


def safe_moves(graph,agents,body_radius,wall_margin):
    """Precalculate whether swept robot centerlines clear ALL static wall edges.

    Unit-square free cells are the physical world approximation. The test is
    exact for straight-line (axial/wait) swept disc center vs these segments;
    it does not include rotation, dynamics, or uncertainty beyond supplied m.
    """
    walls=boundaries(graph)
    need=body_radius+wall_margin
    out={}
    for agent in agents:
        valid={}
        for p in graph.cells:
            for q in motions(graph,agent,p):
                clearance=min(segment_distance(p,q,*edge) for edge in walls)
                if clearance+1e-9 >= need:
                    valid.setdefault(p,[]).append(q)
        out[agent.name]={p:tuple(v) for p,v in valid.items()}
    return out


def viability_cones(graph,agents,safe,H):
    """Individual forward/backward directed reachability without selecting a path.

    Goal is absorbing. Retain states that belong to >=1 full-horizon directed
    start-to-goal walk. These cones alone do not guarantee a simultaneous plan.
    """
    result={}
    for a in agents:
        sm=safe[a.name]
        f=[set() for _ in range(H+1)];f[0].add(a.start)
        for t in range(H):
            for p in f[t]:f[t+1].update(sm.get(p,()))
        b=[set() for _ in range(H+1)];b[H].add(a.goal)
        for t in range(H-1,-1,-1):
            b[t]={p for p in graph.cells if any(q in b[t+1] for q in sm.get(p,()))}
        core=[f[t]&b[t] for t in range(H+1)]
        result[a.name]={'forward':f,'backward':b,'core':core,
                        'goal_reachable_alone': a.goal in f[H],
                        'viable_state_count':sum(map(len,core))}
    return result


def joint_astar(graph, agents, dstar, safe, H, minimum_distance, limit=220000, labels=None):
    """Joint-state A* without priority, route seeds, or Graph Cut.

    Admissible heuristic is the sum of independent shortest remaining steps.
    Arrival cost counts each robot until it first reaches its goal. Within
    this finite directed model, an exhausted search establishes optimality;
    limits or timeout mean no claim of infeasibility.
    """
    names=tuple(a.name for a in agents)
    starts=tuple(a.start for a in agents)
    goals=tuple(a.goal for a in agents)
    costs=[dstar[n].g for n in names]
    if any(math.dist(starts[i],starts[j])<minimum_distance-1e-9
           for i in range(len(names)) for j in range(i+1,len(names))):
        return {'found':False,'reason':'starts violate minimum clearance','expanded':0}
    if labels is not None and any(labels.get((p,0))!=n for p,n in zip(starts,names)):
        return {'found':False,'reason':'start not owned','expanded':0}
    def heuristic(ps):return sum(d[ps[i]] for i,d in enumerate(costs))
    initial=(0,starts)
    q=[(heuristic(starts),0.,0,initial)]
    best={initial:0.}
    parents={initial:None}
    count=0;expanded=0
    while q:
        _,score,_,state=heapq.heappop(q)
        if score!=best.get(state):continue
        t,positions=state
        expanded+=1
        if positions==goals:
            states=[]
            while state is not None:
                states.append(state)
                state=parents[state]
            states.reverse()
            raw={n:[p[1][i] for p in states] for i,n in enumerate(names)}
            arrivals={n:next(tt for tt,p in enumerate(raw[n]) if p==goals[i]) for i,n in enumerate(names)}
            padded={n:seq+[seq[-1]]*(H+1-len(seq)) for n,seq in raw.items()}
            return {'found':True,'expanded':expanded,'optimal_cost':int(score),
                    'arrival':arrivals,'paths':padded,'makespan':max(arrivals.values()),
                    'method':'joint A* over 4-robot product states; zero fixed priority'}
        if expanded>=limit:
            return {'found':False,'reason':'state expansion cap','expanded':expanded,'limit':limit}
        if t>=H or t+max(costs[i][p] for i,p in enumerate(positions))>H:
            continue
        options=[tuple(q for q in safe[n].get(p,()) if labels is None or labels.get((q,t+1))==n)
                 for n,p in zip(names,positions)]
        if any(not opts for opts in options):continue
        # Symmetric move set; prune continuous-time collisions on every transition.
        for nxt in itertools.product(*options):
            if any(dist_to_segment_zero(positions[i],nxt[i],positions[j],nxt[j]) < minimum_distance-1e-9
                   for i in range(len(nxt)) for j in range(i+1,len(nxt))):continue
            if t+1+max(costs[i][nxt[i]] for i in range(len(nxt)))>H:continue
            additional=sum(positions[i]!=goals[i] for i in range(len(nxt)))
            new_score=score+additional
            key=(t+1,nxt)
            if new_score>=best.get(key,float('inf')):continue
            best[key]=new_score;parents[key]=(t,positions);count+=1
            heapq.heappush(q,(new_score+heuristic(nxt),new_score,count,key))
    return {'found':False,'reason':'exhausted finite joint state space', 'expanded':expanded}


def time_potential_unary(graph,agents,dstar,cones,H,scale=100):
    """Soft state potential gated by HARD individual reachability cones."""
    names=[a.name for a in agents]
    distances={a.name:graph.distances(a.start) for a in agents}
    pinned={}
    for a in agents:
        pinned[(a.start,0)]=a.name
        pinned[(a.goal,H)]=a.name
    unary={}
    for t in range(H+1):
        for p in sorted(graph.cells):
            score={}
            for a in agents:
                n=a.name
                if p not in cones[n]['core'][t]:
                    # Discourage unreachable labels; only if not a fixed seed.
                    score[n]=100000
                    continue
                f=distances[n][p];g=dstar[n].g[p]
                optimal=distances[n][a.goal]
                detour=max(0.,f+g-optimal)
                # Reachability/state likelihood from current time wavefront.
                # Normalize desired progress by global path length and horizon.
                desired=min(optimal, max(0., t*optimal/H))
                deviation=abs(f-desired)
                score[n]=int(round(scale*(0.11*detour+0.10*deviation+0.02*g)))
            unary[(p,t)]=score
    return unary,pinned


def optimize_cut(graph,agents,H,unary,pinned,previous=None,passes=2):
    names=sorted(a.name for a in agents)
    edges=list(neighbor_edges(graph,H,spatial_lambda=.5,temporal_lambda=1.0))
    if previous is None:
        labels={key:min(names,key=lambda n:(v[n],n)) for key,v in unary.items()}
    else: labels=dict(previous)
    labels.update(pinned)
    hist=[compute_energy(labels,unary,edges)]
    for _ in range(passes):
        changed=False
        for n in names:
            newer=alpha_move(labels,n,unary,edges,pinned=pinned)
            energy=compute_energy(newer,unary,edges)
            if energy<hist[-1]:
                labels=newer;hist.append(energy);changed=True
        if not changed:break
    return labels,hist


def label_connectivity(graph,agents,labels,H,safe):
    """Directed connectivity to final plane inside each ownership label."""
    result={}
    for a in agents:
        f=[set() for _ in range(H+1)]
        if labels.get((a.start,0))==a.name:
            f[0].add(a.start)
        for t in range(H):
            for p in f[t]:
                for q in safe[a.name].get(p,()):
                    if labels.get((q,t+1))==a.name:f[t+1].add(q)
        b=[set() for _ in range(H+1)]
        if labels.get((a.goal,H))==a.name:b[H].add(a.goal)
        for t in range(H-1,-1,-1):
            b[t]={p for p in graph.cells if labels.get((p,t))==a.name and
                  any(q in b[t+1] for q in safe[a.name].get(p,()))}
        result[a.name]={'connected':a.goal in f[H],
                        'forward_count':sum(map(len,f)),
                        'core_count':sum(len(f[t]&b[t]) for t in range(H+1)),
                        'core': [f[t]&b[t] for t in range(H+1)]}
    return result


def minimum_label_edits_path(graph,agent,cone,safe,H,labels,unary):
    """Find a low-edit path for connectivity feedback (not pinned as a hard seed).

    This is only run AFTER a disconnected graph cut. The node edit price
    favours labels already allocated to the agent. Directed reachability
    gates prevent spurious shortcuts through time.
    """
    name=agent.name
    parent={(agent.start,0):None}
    dist={(agent.start,0):0.}
    # DAG dynamic shortest-path by time slice.
    for t in range(H):
        for p in sorted(cone['core'][t]):
            cur=(p,t)
            if cur not in dist:continue
            for q in safe[name].get(p,()):
                if q not in cone['core'][t+1]:continue
                node=(q,t+1)
                # Large price for stealing other agent's label; small movement penalty.
                price=(4. if labels.get(node)!=name else 0.)+(0.012 if p==q else 0.0)
                # Better score near preferred state wavefront.
                price+=0.0004*unary[node][name]
                nxt=dist[cur]+price
                if nxt<dist.get(node,float('inf'))-1e-9:
                    dist[node]=nxt;parent[node]=cur
    last=(agent.goal,H)
    if last not in parent:return None
    seq=[];s=last
    while s is not None:
        seq.append(s);s=parent[s]
    return seq[::-1]


def repair_soft_flow(graph,agents,dstar,cones,safe,H,iterations=6,passes=1):
    """Alternating potential cut / dynamic directed reachability repair.

    No complete path is provided in advance and no path cell is HARD-pinned.
    If disconnected, least-edit directed candidate walks are used as SOFT
    unary pressure. This is an approximation, not a proof of completeness,
    and does not ensure pairwise swept-tube separation within entire labels.
    """
    unary,pinned=time_potential_unary(graph,agents,dstar,cones,H)
    penalty=defaultdict(lambda:defaultdict(int))
    labels=None
    log=[]
    for iteration in range(iterations+1):
        costs={node:{name:u[name]+penalty[node][name] for name in u} for node,u in unary.items()}
        labels,energy=optimize_cut(graph,agents,H,costs,pinned,previous=labels,passes=passes)
        reachable=label_connectivity(graph,agents,labels,H,safe)
        connected={n:v['connected'] for n,v in reachable.items()}
        log.append({'iteration':iteration,'connected':connected,'energy':energy[-1],
                    'core_count':{n:v['core_count'] for n,v in reachable.items()}})
        if all(connected.values()):break
        for a in agents:
            if connected[a.name]:continue
            path=minimum_label_edits_path(graph,a,cones[a.name],safe,H,labels,costs)
            if path is None:continue
            for (p,t) in path:
                if (p,t) in pinned:continue
                # For each needed cell, a finite preference for the agent.
                # This can be overcome by the geometry/cut boundary cost.
                for other in (n.name for n in agents if n.name!=a.name):
                    penalty[(p,t)][other] += int(800/(1+iteration*.6))
    return {'labels':labels,'history':log,'connected':{n:v['connected'] for n,v in
            label_connectivity(graph,agents,labels,H,safe).items()},
            'hard_path_pins':False,'endpoint_pins':len(pinned)}


def individual_path_in_region(graph, agents, labels, safe, H):
    """Independent directed shortest arrival inside label; NOT multi-robot safe."""
    paths={}; connected={}
    for a in agents:
        parent={(a.start,0):None}
        current={a.start}
        if labels.get((a.start,0))!=a.name:
            connected[a.name]=False;continue
        for t in range(H):
            future=set()
            for p in sorted(current):
                for q in safe[a.name].get(p,()):
                    if labels.get((q,t+1))!=a.name:continue
                    nxt=(q,t+1)
                    if nxt not in parent:parent[nxt]=(p,t)
                    future.add(q)
            current=future
        tail=(a.goal,H)
        if tail not in parent:
            connected[a.name]=False;continue
        out=[];cur=tail
        while cur is not None:
            out.append(cur[0]);cur=parent[cur]
        paths[a.name]=out[::-1]
        connected[a.name]=True
    return paths,connected


def geometry_report(paths, agents, graph, body_radius, wall_margin, pair_distance):
    """Continuous segment safety of a *specific synchronized trajectory set*."""
    walls=boundaries(graph)
    wall_distance=min(segment_distance(p,q,*edge) for seq in paths.values()
                      for p,q in zip(seq,seq[1:]) for edge in walls)
    pair_dist=min_clearance(paths)
    by_t=[]
    H=len(next(iter(paths.values())))-1
    for t in range(H):
        pair_clearance=min(dist_to_segment_zero(paths[i][t],paths[i][t+1],
                                               paths[j][t],paths[j][t+1])
                           for i,j in itertools.combinations(sorted(paths),2))
        wall_clearance=min(segment_distance(seq[t],seq[t+1],*edge)
                           for seq in paths.values() for edge in walls)
        available_tube_radius=max(0.,min(wall_clearance-body_radius-wall_margin,
                                         (pair_clearance-pair_distance)/2.))
        by_t.append({'t':t,'pair_center_distance_m':round(pair_clearance,6),
                     'wall_center_distance_m':round(wall_clearance,6),
                     'max_shared_path_deviation_m':round(available_tube_radius,6)})
    return {'minimum_pair_center_m':pair_dist['distance'],
            'closest_pair':pair_dist['pair'],
            'minimum_wall_center_m':wall_distance,
            'pair_safe':pair_dist['distance']+1e-8>=pair_distance,
            'wall_safe':wall_distance+1e-8>=body_radius+wall_margin,
            'per_transition':by_t,
            'safe_traj':pair_dist['distance']+1e-8>=pair_distance and
                         wall_distance+1e-8>=body_radius+wall_margin}


def soft_safety_feedback(graph,agents,dstar,cones,safe,H,reference_paths,
                         strength=1400):
    """Soft multi-agent FLOW feedback following disconnected/margin-unsafe cut.

    The external feasibility oracle first finds a synchronized collision-safe
    *candidate*, potentially with planned order enumeration. Full candidate
    paths are NOT hard-pinned. Their presence only adjusts finite unary costs;
    a fresh alpha-expansion cut and a separate JOINT A* must still confirm that
    at least one synchronized safe plan exists inside the allocated labels.

    This is a pragmatic constraint-generation step, not a cut-only solution.
    """
    unary,pinned=time_potential_unary(graph,agents,dstar,cones,H)
    for name,seq in reference_paths.items():
        if len(seq)!=H+1:raise ValueError('reference path has incorrect time horizon')
        for t,p in enumerate(seq):
            p=tuple(p)
            for a in agents:
                if a.name!=name:
                    unary[(p,t)][a.name]+=strength
    labels,energy=optimize_cut(graph,agents,H,unary,pinned,passes=3)
    connectivity=label_connectivity(graph,agents,labels,H,safe)
    retained=sum(labels.get((tuple(p),t))==name for name,seq in reference_paths.items()
                 for t,p in enumerate(seq))
    return {'labels':labels,'history':energy,'connected':{n:v['connected'] for n,v in connectivity.items()},
            'hard_complete_path_pins':False,'endpoint_pins':len(pinned),
            'soft_feedback_strength':strength,'candidate_cells_retained':retained,
            'candidate_cell_total':sum(map(len,reference_paths.values()))}


def run(H=30, body_radius=.28, wall_margin=.1, pair_margin=.34, max_joint_states=12000):
    from experiments.state_margin_bridge import margin_schedules
    if H < 1:raise ValueError('horizon must be positive')
    if any(v<0 for v in (body_radius,wall_margin,pair_margin)):
        raise ValueError('radius and margins must be nonnegative')
    graph,agents=make_four_bridge(True)
    dstar,independent=independent_dstar(graph,agents)
    required=2*body_radius+pair_margin
    safe=safe_moves(graph,agents,body_radius,wall_margin)
    cones=viability_cones(graph,agents,safe,H)
    initial=repair_soft_flow(graph,agents,dstar,cones,safe,H,iterations=0,passes=2)
    feedback=repair_soft_flow(graph,agents,dstar,cones,safe,H,iterations=16,passes=2)
    intermediate_paths,_=individual_path_in_region(graph,agents,feedback['labels'],safe,H)
    intermediate_geom=geometry_report(intermediate_paths,agents,graph,body_radius,wall_margin,required) if len(intermediate_paths)==4 else None
    if all(feedback['connected'].values()):
        inside_pre=joint_astar(graph,agents,dstar,safe,H,required,
                              limit=max_joint_states,labels=feedback['labels'])
    else:
        inside_pre={'found':False,'reason':'not all labels directed-connected'}
    oracle=margin_schedules(graph,agents,dstar,H,[required])[str(required)]
    # Robust floating-point key reconstruction: use sole result when needed.
    if not oracle.get('found'):
        guided=None
        inside_post={'found':False,'reason':'no margin-valid witness found by enumerated-order feasibility oracle'}
    else:
        reference_paths={n:[tuple(p) for p in seq] for n,seq in oracle['paths'].items()}
        # Reject if a feasibility oracle route fails the wall-swept geometry rule.
        if any(q not in safe[n].get(p,()) for n,seq in reference_paths.items()
               for p,q in zip(seq,seq[1:])):
            guided=None
            inside_post={'found':False,'reason':'oracle candidate fails wall clearance'}
        else:
            guided=soft_safety_feedback(graph,agents,dstar,cones,safe,H,reference_paths)
            if all(guided['connected'].values()):
                inside_post=joint_astar(graph,agents,dstar,safe,H,required,
                                        limit=max_joint_states,labels=guided['labels'])
            else:
                inside_post={'found':False,'reason':'feedback cut disconnected at least one agent'}
    result={'scenario':'four_robot_single_bridge_with_bays',
            'model':{'cell_size_m':1,'step_seconds':1,'horizon_steps':H,
                     'disc_radius_m':body_radius,'wall_extra_margin_m':wall_margin,
                     'pair_extra_margin_m':pair_margin,'pair_required_center_m':required,
                     'wall_swept_clearance':'straight transitions vs free-cell-union boundary',
                     'dynamic_clearance':'synchronized linear straight-line transitions',
                     'fixed_robot_priority':False},
            'grid':[list(p) for p in sorted(graph.cells)],
            'agents':{a.name:{'start':list(a.start),'goal':list(a.goal),
                      'independent_shortest_steps':len(independent[a.name])-1} for a in agents},
            'reachability_cones':{n:{'goal_reachable_alone':v['goal_reachable_alone'],
                              'viable_state_count':v['viable_state_count'],
                              'per_t':[len(s) for s in v['core']]} for n,v in cones.items()},
            'initial_cut':{'connected':initial['connected'],'history':initial['history'],
                           'frames':four_label_frames(graph,initial['labels'],[a.name for a in agents],H)},
            'directed_feedback_cut':{'connected':feedback['connected'],'history':feedback['history'],
                           'hard_complete_path_pins':False,
                           'frames':four_label_frames(graph,feedback['labels'],[a.name for a in agents],H),
                           'independent_paths':{n:[list(p) for p in seq] for n,seq in intermediate_paths.items()},
                           'independent_path_geometry':intermediate_geom,
                           'joint_restricted':{k:v for k,v in inside_pre.items() if k!='paths'}},
            'safety_oracle':{'found':oracle['found'],'method':'enumerate 24 prioritized A* planning orders without fixed priority',
                             'feasible_orders':oracle.get('feasible_orders',0),
                             'arrival':oracle.get('arrival'),
                             'minimum_center_distance_m':oracle.get('minimum_distance_m',{}).get('distance') if oracle['found'] else None},
            'safety_feedback_cut':None,
            'notes':[
                'Individual forward/backward cones only certify single-agent reachability.',
                'The graph cut alone DOES NOT guarantee directed reachability or multi-agent separation.',
                'Reachability feedback computes a soft candidate walk AFTER each disconnected cut; no hard full path pin.',
                'Safety feedback uses a separate 24-order A* oracle to propose safe paths as SOFT pressure, not proof of joint optimality.',
                'Joint product-state A* restricted to the final cut certifies a feasible synchronized trajectory when found.',
                'The cut labels are not generally safe for arbitrary motion within the labelled region; only verified trajectories and their conservative clearance tubes are safe.',
                'All collision results are conditional on unit-square geometry, circular bodies and synchronous linear motion.'
            ]}
    if guided is not None:
        result['safety_feedback_cut']={'connected':guided['connected'],
            'hard_complete_path_pins':False,
            'soft_feedback_strength':guided['soft_feedback_strength'],
            'candidate_cells_retained':guided['candidate_cells_retained'],
            'candidate_cell_total':guided['candidate_cell_total'],
            'frames':four_label_frames(graph,guided['labels'],[a.name for a in agents],H),
            'joint_restricted':{k:v for k,v in inside_post.items() if k!='paths'}}
        if inside_post.get('found'):
            valid_paths=inside_post['paths']
            geom=geometry_report(valid_paths,agents,graph,body_radius,wall_margin,required)
            result['safety_feedback_cut']['joint_paths']={n:[list(p) for p in seq]
                                                          for n,seq in valid_paths.items()}
            result['safety_feedback_cut']['geometry']=geom
    return result

