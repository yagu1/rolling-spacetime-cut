"""Reachability-constrained and margin-aware XYT planning experiment.

The experiment deliberately distinguishes three different computations:
  * single-agent forward/backward viability cones (not full 4-agent feasibility),
  * a multi-label graph cut using time-dependent potentials (not connectivity-safe),
  * a joint-state A* feasibility search with continuous segment separation.

An optional soft flow-pressure feedback into the cut is EXPERIMENTAL; no hard
completed paths are fixed in the cut. The joint A* paths are independent safety
witnesses and are not claimed to be generated by the cut itself.
"""
