def render_tie_break(report:dict,output:Path)->None:
    scenarios=[('No preference',report['scenarios']['bridge_with_bays']),
               ('Tiny favor A',report['bridge_tie_break']['favor_A']),
               ('Tiny favor B',report['bridge_tie_break']['favor_B'])]
    fig,axes=plt.subplots(1,3,figsize=(13.4,6.2),sharey=True,sharex=True)
    for ax,(title,scenario) in zip(axes,scenarios):
        H=scenario['horizon_steps']
        for name,col in [('A',C_A),('B',C_B)]:
            path=scenario['joint']['paths'][name]
            ts=[t for t,p in enumerate(path) if p[1]==2 and 2<=p[0]<=10]
            xs=[path[t][0] for t in ts]
            ax.plot(xs,ts,'-o',lw=2.6,ms=4,color=col,label=name)
        ax.set_ylim(H+1,-1);ax.set_xlim(1.5,10.5)
        arr=scenario['joint']['arrival_steps']
        ax.set_title(f'{title}\nA={arr["A"]} steps; B={arr["B"]} steps',fontsize=11)
        ax.set_xlabel('Bridge x')
        ax.grid(alpha=.25,linestyle=':')
        ax.legend(loc='lower left')
    axes[0].set_ylabel('Time step')
    fig.suptitle('Single bridge: arrival-time tie-break, not an exclusive reservation',
                 fontsize=14,weight='bold')
    fig.text(.5,.018,'The primary objective is the sum of arrival times; the small bias '
                   'chooses between otherwise equal-cost orderings.',ha='center',fontsize=9)
    fig.tight_layout(rect=(0,.04,1,.94))
    fig.savefig(output/'bridge_tie_break.png',dpi=165)
    plt.close(fig)


