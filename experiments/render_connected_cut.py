C_A = '#23799c'
C_B = '#e68b38'
C_BG = '#f6f8fa'
C_WALL = '#dce3e9'
C_CORE = '#fefefe'
C_EDGE = '#252d35'


def font(size: int, bold: bool=False):
    paths = ['/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf' if bold else
             '/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf',
             'C:/Windows/Fonts/arialbd.ttf' if bold else 'C:/Windows/Fonts/arial.ttf']
    for path in paths:
        try:
            return ImageFont.truetype(path, size)
        except OSError:
            pass
    return ImageFont.load_default()


def point(p):
    return tuple(p)


def make_map_frame(scenario: dict, t: int, *, scale: int = 46) -> Image.Image:
    grid = {point(p) for p in scenario['grid']}
    xs = [p[0] for p in grid]; ys = [p[1] for p in grid]
    xmin,xmax=min(xs),max(xs); ymin,ymax=min(ys),max(ys)
    wd=(xmax-xmin+1)*scale + 80
    ht=(ymax-ymin+1)*scale + 220
    margin_x, margin_y=40,91
    img=Image.new('RGB',(wd,ht),'#ffffff')
    draw=ImageDraw.Draw(img)
    title=scenario['scenario'].replace('_',' ').title()
    draw.text((22,16),f'{title}   |   t = {t:02d} / {scenario["horizon_steps"]}',
              fill=C_EDGE,font=font(20,True))
    draw.text((22,51),'Connected, path-witness-seeded XYT graph cut',
              fill='#697684',font=font(14))
    frame=scenario['connected_cut']['frames'][t]
    ownership={point(p): label for label in ('A','B') for p in frame[label]}
    core={label:{point(p) for p in scenario['connected_cut']['cores'][label]['core_cells_by_t'][t]}
          for label in ('A','B')}
    def rect(p):
        x,y=p
        x0=margin_x+(x-xmin)*scale
        y0=margin_y+(y-ymin)*scale
        return x0,y0,x0+scale,y0+scale
    for y in range(ymin,ymax+1):
        for x in range(xmin,xmax+1):
            p=(x,y)
            box=rect(p)
            if p not in grid:
                fill=C_WALL
            else:
                label=ownership[p]
                fill=('#9cc9d8' if label=='A' else '#f4c99c')
                if p not in core[label]:
                    fill=('#d7e9ed' if label=='A' else '#f9e9d8')
            draw.rectangle(box,fill=fill,outline='#ffffff',width=1)
    # Bold black segment exactly where neighboring XY cells get different labels.
    for a,b in frame['boundary_edges']:
        ax,ay=point(a); bx,by=point(b)
        x0,y0,_,_=rect((ax,ay))
        if ax!=bx:
            px = x0+scale if bx>ax else x0
            draw.line((px,y0,px,y0+scale),fill=C_EDGE,width=5)
        else:
            py = y0+scale if by>ay else y0
            draw.line((x0,py,x0+scale,py),fill=C_EDGE,width=5)
    # Goal positions remain visible, independent of whether agent has arrived.
    for agent_name,color in (('A',C_A),('B',C_B)):
        end=point(scenario['agents'][agent_name]['goal'])
        x0,y0,x1,y1=rect(end)
        draw.ellipse((x0+scale*.3,y0+scale*.3,x1-scale*.3,y1-scale*.3),
                     fill='#fff',outline=color,width=2)
        draw.text((x0+scale*.27,y0+scale*.28),'G',fill=color,font=font(16,True))
    for agent_name,color in (('A',C_A),('B',C_B)):
        route=scenario['joint']['paths'][agent_name]
        p=point(route[t])
        x0,y0,x1,y1=rect(p)
        draw.ellipse((x0+scale*.13,y0+scale*.13,x1-scale*.13,y1-scale*.13),
                     fill=color,outline='white',width=3)
        draw.text((x0+scale*.34,y0+scale*.30),agent_name,
                  fill='white',font=font(15,True))
    caption_y=margin_y+(ymax-ymin+1)*scale+12
    draw.text((22,caption_y),f'A blue / B orange  |  Border edges: {frame["spatial_boundary_count"]}  |  Time flips: {frame["temporal_switch_count"]}',
              fill=C_EDGE,font=font(14))
    draw.text((22,caption_y+27),'Pale tiles: labeled cells not certified on a Start-to-Goal directed walk',
              fill='#697684',font=font(12))
    draw.text((22,caption_y+49),'Colored circles: collision-checked joint A* path witness',
              fill='#697684',font=font(12))
    return img


def save_gif_and_contact(scenario:dict, output:Path, shortname:str)->None:
    H=scenario['horizon_steps']
    frames=[make_map_frame(scenario,t) for t in range(H+1)]
    frames[0].save(output / f'{shortname}_cut.gif',save_all=True,append_images=frames[1:],
                   duration=210,loop=0,optimize=True)
    selected=sorted(set([0,H//4,H//2,(3*H)//4,H]))
    # Contact sheet with 5 time slices.
    imgs=[frames[i] for i in selected]
    w,h=imgs[0].size
    cols=2;rows=3
    sheet=Image.new('RGB',(cols*w,rows*h),'#fff')
    for i,img in enumerate(imgs):
        sheet.paste(img,((i%cols)*w,(i//cols)*h))
    d=ImageDraw.Draw(sheet)
    d.text((w+24,h*2+40),'Animation: '+f'{shortname}_cut.gif',fill=C_EDGE,font=font(24,True))
    sheet.save(output / f'{shortname}_cut_slices.png', optimize=True)


def render_bridge_xt(report:dict,output:Path)->None:
    base=report['scenarios']['bridge_with_bays']['connected_cut']['frames']
    smooth=report['bridge_temporal_smoothing']['frames']
    witness=report['scenarios']['bridge_with_bays']['joint']['paths']
    cases=[('Baseline: temporal penalty 0.6',base),
           ('Smoother: temporal penalty 3.0',smooth)]
    H=len(base)-1
    cmap=ListedColormap([C_A,C_B])
    fig,axes=plt.subplots(1,2,figsize=(12.8,8.3),sharex=True,sharey=True)
    for ax,(title,frames) in zip(axes,cases):
        mat=[]
        for t in range(H+1):
            a={point(p) for p in frames[t]['A']}
            mat.append([0 if (x,2) in a else 1 for x in range(2,11)])
        ax.imshow(mat,origin='upper',interpolation='nearest',aspect='auto',
                  extent=(1.5,10.5,H+0.5,-0.5),cmap=cmap,vmin=0,vmax=1,alpha=0.83)
        # Draw exactly the cut edges in the x-t section as black stair edges.
        for ti,row in enumerate(mat):
            for j in range(8):
                if row[j]!=row[j+1]:
                    x=float(j+2)+0.5
                    ax.plot((x,x),(ti-0.5,ti+0.5),c=C_EDGE,lw=1.8)
            if ti:
                prev=mat[ti-1]
                for j in range(9):
                    if row[j]!=prev[j]:
                        x=float(j+2)
                        ax.plot((x-.5,x+.5),(ti-.5,ti-.5),c=C_EDGE,lw=1.8)
        # Path witness samples only while occupying the center bridge line.
        for label,color,marker in [('A','#07344a','o'),('B','#834100','s')]:
            for t,p in enumerate(witness[label]):
                x,y=p
                if y==2 and 2<=x<=10:
                    ax.scatter([x],[t],s=16,marker=marker,c=color,edgecolors='white',
                               linewidths=.5,zorder=8)
        ax.set_title(title,fontsize=12,weight='bold',pad=12)
        ax.set_xlabel('Bridge cell x (y = 2)')
        ax.set_xlim(1.5,10.5);ax.set_ylim(H+.5,-.5)
        ax.set_xticks(range(2,11));ax.set_yticks(range(0,H+1,2))
        ax.set_xticks([x+.5 for x in range(2,10)], minor=True)
        ax.grid(which='minor',axis='x',alpha=.2)
    axes[0].set_ylabel('Time step (downward)')
    fig.suptitle('Bridge space-time cut: temporal interface and ownership changes',
                 fontsize=15,weight='bold')
    fig.text(.5,.025,'Black segments = actual XYT cut boundary; dots/squares = A/B joint-path occupancy. '
                   'Higher smoothing can create spatial islands.',
             ha='center',fontsize=10)
    fig.tight_layout(rect=(0,.045,1,.945))
    fig.savefig(output/'bridge_xt_boundary.png',dpi=170)
    plt.close(fig)


def render_seed_goal_xyt(scenario:dict, output:Path, basename:str)->None:
    """3D diagram with real consecutive directed edges (not S->all G shortcuts)."""
    from mpl_toolkits.mplot3d import Axes3D  # noqa: F401
    from mpl_toolkits.mplot3d.art3d import Line3DCollection
    grid={point(v) for v in scenario['grid']}
    H=scenario['horizon_steps']
    fig=plt.figure(figsize=(12.6,7.5))
    ax=fig.add_subplot(111,projection='3d',computed_zorder=False)
    layers=sorted(set([0,H//4,H//2,(3*H)//4,H]))
    for t in layers:
        edges=[]
        for x,y in grid:
            for q in ((x+1,y),(x,y+1)):
                if q in grid:
                    edges.append([(x,y,t),(q[0],q[1],t)])
        ax.add_collection3d(Line3DCollection(edges,colors='#a9b5bb',linewidths=.45,alpha=.24))
        for p in grid:
            ax.scatter(p[0],p[1],t,s=1.5,color='#bac2c9',alpha=.5,depthshade=False)
    for name,color in [('A',C_A),('B',C_B)]:
        seed=scenario['agents'][name]['start']
        goal=scenario['agents'][name]['goal']
        earliest=scenario['agents'][name]['independent_steps']
        coords=scenario['joint']['paths'][name]
        ax.plot(*zip(*[(p[0],p[1],t) for t,p in enumerate(coords)]),c=color,
                linewidth=3.0,alpha=.93,label=f'{name}: connected directed witness')
        ax.scatter(seed[0],seed[1],0,marker='*',s=130,color=color,
                   edgecolors='black',linewidths=.5,depthshade=False)
        ax.text(seed[0],seed[1],0,f'  S{name}',color=color,fontsize=10,weight='bold')
        ax.plot([goal[0],goal[0]],[goal[1],goal[1]],[earliest,H],
                c=color,ls='--',lw=1.8,alpha=.7)
        arr=next(t for t,p in enumerate(coords) if p==goal)
        ax.scatter(goal[0],goal[1],arr,marker='D',color=color,s=85,
                   edgecolors='white',linewidths=.5,depthshade=False)
        ax.text(goal[0],goal[1],arr,f'  G{name}@t{arr}',color=color,
                fontsize=10,weight='bold')
    ax.set_xlabel('x / grid cells',labelpad=12)
    ax.set_ylabel('y / grid cells',labelpad=12)
    ax.set_zlabel('t / discrete steps',labelpad=8)
    ax.set_zlim(0,H)
    ax.set_xlim(min(p[0] for p in grid)-.3,max(p[0] for p in grid)+.3)
    ax.set_ylim(min(p[1] for p in grid)-.3,max(p[1] for p in grid)+.3)
    ax.view_init(elev=20,azim=-57)
    ax.set_box_aspect((2.4,1.0,2.4),zoom=.87)
    ax.legend(loc='upper left',bbox_to_anchor=(.01,.98),fontsize=10)
    fig.suptitle('XYT seed connectivity: START at t=0, GOAL at any valid future step',
                 fontsize=14,weight='bold',y=.97)
    fig.text(.5,.025,'Dashed vertical lines: allowed goal-time columns; solid paths: '
                   'actual connected consecutive-time motion edges (including wait).',
             ha='center',fontsize=10)
    fig.savefig(output/f'{basename}_seeds_xyt.png',dpi=165,bbox_inches='tight')
    plt.close(fig)


