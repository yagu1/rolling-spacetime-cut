def main():
    ap=argparse.ArgumentParser()
    ap.add_argument('--report',type=Path,default=Path('output/connected_cut/report.json'))
    ap.add_argument('--output',type=Path,default=Path('docs/figures'))
    args=ap.parse_args()
    args.output.mkdir(parents=True,exist_ok=True)
    r=json.loads(args.report.read_text(encoding='utf8'))
    for name,short in [('two_corridors','two_corridors'),('bridge_with_bays','bridge')]:
        item=r['scenarios'][name]
        save_gif_and_contact(item,args.output,short)
        render_seed_goal_xyt(item,args.output,short)
    smooth_scene=copy.deepcopy(r['scenarios']['bridge_with_bays'])
    smooth_scene['connected_cut']['frames']=r['bridge_temporal_smoothing']['frames']
    smooth_scene['connected_cut']['cores']=r['bridge_temporal_smoothing']['cores']
    save_gif_and_contact(smooth_scene,args.output,'bridge_smooth')
    render_bridge_xt(r,args.output)
    render_no_bays(r['scenarios']['bridge_no_bays'],args.output)
    render_tie_break(r,args.output)
    render_html(r,args.output)
    print('Wrote',', '.join(p.name for p in sorted(args.output.iterdir()) if p.is_file()))

if __name__=='__main__':
    main()
